"""Write dell-health.yml, the dell_health module for the iDRAC.

The dell module in snmp_exporter's snmp.yml walks three whole subtrees of the
iDRAC MIB: 2,211 series and 26 seconds a scrape on linds-proxmox-01's iDRAC8,
most of it the event log, PCI devices and firmware. dell_health takes the
same metric definitions (OIDs, indexes, enum values) for component health
only, and adds each component's name as a label. That is 80 series in about
5 seconds.

Left out on purpose: the RAID controller, its battery, and the physical and
virtual disks. storage-health-exporter reads those from perccli on the host
(base/monitoring/proxmox-storage-health.yaml), so they would only alert
twice.

Run it again after a snmp_exporter upgrade, with the image's version:

  curl -sSfL https://raw.githubusercontent.com/prometheus/snmp_exporter/v0.30.1/snmp.yml \
    | yq -o=json '.modules.dell' \
    | python3 -I monitoring-hardware/snmp/build-dell-health.py v0.30.1 \
    > monitoring-hardware/snmp/dell-health.yml
"""

import copy
import json
import sys

# Metric -> the column that names the component. None for a scalar.
SPEC = {
    "globalSystemStatus": None,
    "systemPowerState": None,
    "powerSupplyStatus": "powerSupplyLocationName",
    "powerSupplyOutputWatts": "powerSupplyLocationName",
    "amperageProbeReading": "amperageProbeLocationName",
    "amperageProbeStatus": "amperageProbeLocationName",
    "coolingDeviceReading": "coolingDeviceLocationName",
    "coolingDeviceStatus": "coolingDeviceLocationName",
    "temperatureProbeReading": "temperatureProbeLocationName",
    "temperatureProbeStatus": "temperatureProbeLocationName",
    "voltageProbeStatus": "voltageProbeLocationName",
    "memoryDeviceStatus": "memoryDeviceLocationName",
    "processorDeviceStatus": "processorDeviceFQDD",
    "systemBatteryStatus": "systemBatteryLocationName",
    "intrusionStatus": "intrusionLocationName",
}

# The MIB gives these in tenths; Prometheus gets whole units.
SCALE = {"temperatureProbeReading": 0.1, "powerSupplyOutputWatts": 0.1}


def oid_key(oid):
    return [int(part) for part in oid.split(".")]


def build(dell):
    by_name = {m["name"]: m for m in dell["metrics"]}
    metrics, get, walk = [], [], set()
    for name, label in SPEC.items():
        metric = copy.deepcopy(by_name[name])
        if name in SCALE:
            metric["scale"] = SCALE[name]
        if metric.get("indexes"):
            walk.add(metric["oid"])
        else:
            get.append(metric["oid"] + ".0")
        if label:
            column = by_name[label]
            metric["lookups"] = [{
                "labels": [i["labelname"] for i in metric["indexes"]],
                "labelname": label,
                "oid": column["oid"],
                # OctetString in the MIB, which snmp_exporter shows as hex.
                "type": "DisplayString",
            }]
            walk.add(column["oid"])
        metrics.append(metric)
    return {"get": get, "walk": sorted(walk, key=oid_key), "metrics": metrics}


def scalar(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    return json.dumps(value)


def emit(value, indent=0):
    """YAML for dicts, lists and scalars. Keys of enum_values stay integers."""
    pad = "  " * indent
    lines = []
    if isinstance(value, dict):
        for key, item in value.items():
            key = int(key) if isinstance(key, str) and key.isdigit() else key
            if isinstance(item, (dict, list)) and item:
                lines.append(f"{pad}{key}:")
                lines.extend(emit(item, indent + 1))
            elif isinstance(item, dict):
                lines.append(f"{pad}{key}: {{}}")
            elif isinstance(item, list):
                lines.append(f"{pad}{key}: []")
            else:
                lines.append(f"{pad}{key}: {scalar(item)}")
    else:
        for item in value:
            if isinstance(item, (dict, list)):
                inner = emit(item, indent + 1)
                lines.append(f"{pad}- {inner[0].lstrip()}")
                lines.extend(inner[1:])
            else:
                lines.append(f"{pad}- {scalar(item)}")
    return lines


def main():
    version = sys.argv[1] if len(sys.argv) > 1 else "unknown"
    module = build(json.load(sys.stdin))
    print(f"# Generated by build-dell-health.py from the dell module of snmp_exporter")
    print(f"# {version}'s snmp.yml. Do not edit by hand: change SPEC there and run it again.")
    print("\n".join(emit({"modules": {"dell_health": module}})))


if __name__ == "__main__":
    main()
